// Port of rust/crates/campfire/src/controllers.rs
//
// The route table from `reference/config/routes.rb` (plus the framework routes `bin/rails routes`
// lists: Active Storage, Turbo Native navigation, Action Mailbox, `/up`), and a router that matches the
// way Rails' Journey does.
//
// Kestrel only sees `/cable` (a Falco endpoint) and, for everything else, `dispatch`, which picks the
// *first* route in table order whose verb and pattern match, exactly as Rails does. That matters:
// `GET /rooms/opens` is `rooms#show` with `id: "opens"` because `resources :rooms` is drawn before
// `namespace :rooms`. Patterns use Rails syntax: `:param` matches `[^/.?]+`, `*glob` matches lazily,
// and `(.:format)` is the optional format suffix (so `/rooms/1.json` sets `params[:format]`). Path
// params are percent-decoded and merged over query and body params, together with `controller` and
// `action`.
//
// The module is `RouteTable` because F# can't have a module `Controllers` beside the namespace of that
// name that holds the controllers themselves.
//
// ## Porting a controller
//
// Add `Controllers/Rooms.fs` (etc.) before this file in the project, write `show (c: Ctx)` actions that
// start with their before-action chain (see `Concerns`), and put `Rooms.show` in the matching rows in
// place of `unported "rooms#show"`, which answers 501 until its controller lands. Declared routes whose
// action Rails doesn't define (e.g. `first_runs#edit`) answer 404 like
// `AbstractController::ActionNotFound`: they map to `actionNotFound`. Never reorder, add or remove rows:
// the table must stay identical to `bin/rails routes` (checked by the tests against
// `vectors/campfire_routes.json`, generated by `reference-tools/campfire/routes.rb`).

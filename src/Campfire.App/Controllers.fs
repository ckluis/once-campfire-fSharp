type Route =
    { Verb: string
      /// The Rails path spec, e.g. `/rooms/:room_id/messages(.:format)`. Compiled into a regex; kept for
      /// the test that compares the table with `bin/rails routes`.
      Pattern: string
      /// `controller#action`, as `bin/rails routes` prints it.
      Endpoint: string
      Defaults: (string * string) list
      Action: ActionFn
      Regex: Regex
      Names: string[] }

    member this.Controller: string =
        match this.Endpoint.IndexOf '#' with
        | -1 -> this.Endpoint
        | i -> this.Endpoint.Substring(0, i)

    member this.ActionName: string =
        match this.Endpoint.IndexOf '#' with
        | -1 -> ""
        | i -> this.Endpoint.Substring(i + 1)

/// A declared route whose action the controller doesn't define (`AbstractController::ActionNotFound`).
module private Fallbacks =
    let actionNotFound (_: Ctx) : Task<Result<Response, Error>> = Task.FromResult(Error NotFound)

    /// A declared route whose controller doesn't exist, e.g. `resource :settings` under rooms: the
    /// reference answers 500 (the controller constant fails to load).
    let missingController (c: Ctx) : Task<Result<Response, Error>> =
        let endpoint =
            match c.Current<MatchedRoute>() with
            | ValueSome route -> route.Endpoint
            | ValueNone -> "?"
        Task.FromResult(Error(Internal(exn $"uninitialized constant for {endpoint}")))

    /// A route whose controller isn't ported yet (Phase 5's later units): 501, and a log line saying which.
    let unported (endpoint: string) : ActionFn =
        fun c ->
            c.Kit.Logger.LogError("route {Endpoint} is not ported yet", endpoint)
            Task.FromResult(Error(Status 501))

/// `Rails::HealthController`
module Health =
    let show (c: Ctx) : Task<Result<Response, Error>> =
        act {
            let! format = c.RespondTo [ Format.Html; Format.Json ]
            if format = Format.Json then
                let timestamp = DateTimeOffset.FromUnixTimeSeconds(c.Now().ToUnixTimeSeconds()).ToString("yyyy-MM-dd'T'HH:mm:ss'Z'")
                return c.Json(Status.Ok, Value.Object [ "status", Value.String "up"; "timestamp", Value.String timestamp ])
            else
                return c.Html """<!DOCTYPE html><html><body style="background-color: green"></body></html>"""
        }

/// `Turbo::Native::NavigationController` (turbo-rails)
module TurboNative =
    let recede (c: Ctx) : Task<Result<Response, Error>> = act { return c.Html "Going back…" }

    let resume (c: Ctx) : Task<Result<Response, Error>> = act { return c.Html "Staying put…" }

    let refresh (c: Ctx) : Task<Result<Response, Error>> = act { return c.Html "Refreshing…" }

/// Action Mailbox's ingress and conductor routes, which Campfire doesn't use.
module Mailbox =
    /// `ActionMailbox::BaseController#ensure_configured`: no ingress is configured.
    let ingressNotConfigured (c: Ctx) : Task<Result<Response, Error>> = act { return c.Head Status.NotFound }

    /// `Rails::Conductor::BaseController`: CSRF first, then `ensure_development_env`.
    let conductor (c: Ctx) : Task<Result<Response, Error>> =
        act {
            do! c.VerifyAuthenticityToken()
            return c.Head Status.Forbidden
        }


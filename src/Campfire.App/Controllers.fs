    /// One verb's routes in table order, indexed by the first segment of their pattern: every pattern
    /// starts with a literal first segment (and `(.:format)` may follow it), so a path's first segment,
    /// cut at its first dot, names the only routes that can match it. (Rust asks a `RegexSet` for the
    /// first of a verb's patterns that match; .NET has none.)
    type private VerbRoutes =
        { Verb: string
          ByFirstSegment: Dictionary<string, Route[]> }

    let private firstSegmentOfPattern (pattern: string) : string =
        let rest = pattern.Substring 1
        let stop = rest.IndexOfAny [| '/'; '('; ':'; '*' |]
        if stop < 0 then rest else rest.Substring(0, stop)

    let private firstSegmentOfPath (path: string) : string =
        let rest = path.Substring 1
        let stop = rest.IndexOfAny [| '/'; '.' |]
        if stop < 0 then rest else rest.Substring(0, stop)

    let private byVerb: Lazy<Dictionary<string, VerbRoutes>> =
        lazy
            (let verbs = Dictionary<string, VerbRoutes>()
             for verb in routes.Value |> Array.map (fun route -> route.Verb) |> Array.distinct do
                 let ofVerb = routes.Value |> Array.filter (fun route -> route.Verb = verb)
                 let index = Dictionary<string, Route[]>(StringComparer.Ordinal)
                 for segment in ofVerb |> Array.map (fun route -> firstSegmentOfPattern route.Pattern) |> Array.distinct do
                     index[segment] <- ofVerb |> Array.filter (fun route -> firstSegmentOfPattern route.Pattern = segment)
                 verbs[verb] <- { Verb = verb; ByFirstSegment = index }
             verbs)

    /// `Journey::Router::Utils.normalize_path`: one leading slash, repeated slashes squeezed,
    /// trailing slashes dropped, percent-escapes upcased.
    let normalizePath (path: string) : string =
        let normalized = StringBuilder(path.Length + 1)
        for c in "/" + path do
            if not (c = '/' && normalized.Length > 0 && normalized[normalized.Length - 1] = '/') then normalized.Append c |> ignore
        while normalized.Length > 1 && normalized[normalized.Length - 1] = '/' do
            normalized.Length <- normalized.Length - 1
        let text = normalized.ToString()
        if text.Contains '%' then
            Regex.Replace(text, "%[a-fA-F0-9]{2}", (fun (m: Match) -> m.Value.ToUpperInvariant()), RegexOptions.CultureInvariant)
        else
            text

    /// `Journey::Router::Utils.unescape_uri`, then Rails' check that the parameter is valid UTF-8
    /// (`ActionController::BadRequest` otherwise).
    let private unescapeUri (value: string) : Result<string, Error> =
        let source = Encoding.UTF8.GetBytes value
        let bytes = ResizeArray<byte>(source.Length)
        let hex (b: byte) = if Char.IsAsciiHexDigit(char b) then Convert.ToInt32(string (char b), 16) else -1
        let mutable i = 0
        while i < source.Length do
            if source[i] = byte '%' && i + 2 < source.Length && hex source[i + 1] >= 0 && hex source[i + 2] >= 0 then
                bytes.Add(byte (hex source[i + 1] * 16 + hex source[i + 2]))
                i <- i + 3
            else
                bytes.Add source[i]
                i <- i + 1
        try
            Ok(UTF8Encoding(false, true).GetString(bytes.ToArray()))
        with :? DecoderFallbackException ->
            Error(BadRequest "Invalid path parameters: Invalid encoding")

    /// A matched route's path parameters: its defaults, then its captures (percent-decoded), then
    /// `controller` and `action`.
    let pathParams (route: Route) (m: Match) : Result<ParamMap, Error> =
        let pathParams = ParamMap()
        for (name, value) in route.Defaults do
            pathParams.Insert(name, Param.Str value)
        let mutable failure = None
        for i in 0 .. route.Names.Length - 1 do
            let group = m.Groups[i + 1]
            if failure.IsNone && group.Success then
                match unescapeUri group.Value with
                | Ok value -> pathParams.Insert(route.Names[i], Param.Str value)
                | Error e -> failure <- Some e
        match failure with
        | Some e -> Error e
        | None ->
            pathParams.Insert("controller", Param.Str route.Controller)
            pathParams.Insert("action", Param.Str route.ActionName)
            Ok pathParams

    /// The first route matching `method` and the normalized `path`, with its path parameters
    /// (defaults, then captures, then `controller`/`action`). HEAD requests match GET routes.
    let recognize (meth: string) (path: string) : Result<(Route * ParamMap) option, Error> =
        let verb = if meth = "HEAD" then "GET" else meth
        match byVerb.Value.TryGetValue verb with
        // Every pattern starts with a slash, so a path that doesn't can't match.
        | _ when path.Length = 0 || path[0] <> '/' -> Ok None
        | false, _ -> Ok None
        | true, candidates ->
            match candidates.ByFirstSegment.TryGetValue(firstSegmentOfPath path) with
            | false, _ -> Ok None
            | true, routes ->
                let mutable found = None
                let mutable i = 0
                while found.IsNone && i < routes.Length do
                    let m = routes[i].Regex.Match path
                    if m.Success then found <- Some(routes[i], m)
                    i <- i + 1
                match found with
                | None -> Ok None
                | Some(route, m) -> pathParams route m |> Result.map (fun pathParams -> Some(route, pathParams))

    /// `params` is body params, then query params, then path params (`request.parameters`).
    let private installPathParams (c: Ctx) (pathParams: ParamMap) : unit =
        c.Params.Merge pathParams
        c.PathParams.Merge pathParams

    /// The single entry point for everything but `/cable`: find the route, install its path params, run
    /// its action.
    let dispatch (c: Ctx) : Task<Result<Response, Error>> =
        match recognize c.Request.Method (normalizePath c.Request.Path) with
        | Error e -> Task.FromResult(Error e)
        | Ok None -> Task.FromResult(Error NotFound)
        | Ok(Some(route, pathParams)) ->
            installPathParams c pathParams
            c.SetCurrent { Endpoint = route.Endpoint }
            route.Action c

//! Prints the Unicode tables the F# helpers need to behave as Rust's `char` methods do, as F# source
//! for `src/Campfire.Views/Helpers/UnicodeTables.fs`: `char::is_alphanumeric` (what `User#initials`'s
//! word-boundary check calls a word character) and the characters whose upper or lower case is more
//! than one character (`str::to_uppercase`, `capitalize`). Run by `bin/views-differential --unicode`.

fn ranges(test: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for code in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(code) else { continue };
        if test(c) {
            match out.last_mut() {
                Some(last) if last.1 + 1 == code => last.1 = code,
                _ => out.push((code, code)),
            }
        }
    }
    out
}

fn main() {
    println!("// Generated by reference-tools/views/differential/src/bin/unicode.rs (bin/views-differential --unicode)");
    println!("// from the Rust standard library's Unicode data. Do not edit.");
    println!("module internal Campfire.Views.Helpers.UnicodeTables");
    println!();
    println!("/// `char::is_alphanumeric` as inclusive code point ranges, in order.");
    println!("let alphanumeric: struct (int * int)[] =");
    println!("    [|");
    for chunk in ranges(char::is_alphanumeric).chunks(6) {
        let line: Vec<String> = chunk.iter().map(|(a, b)| format!("struct (0x{a:X}, 0x{b:X})")).collect();
        println!("        {}", line.join("; "));
    }
    println!("    |]");
    println!();
    for (name, doc, upper) in [
        ("upperSimple", "`char::to_uppercase` where it is one character and not the character itself", true),
        ("lowerSimple", "`char::to_lowercase` where it is one character and not the character itself", false),
    ] {
        println!("/// {doc}: pairs of code point and its mapping, flat, in order of code point.");
        println!("let {name}: int[] =");
        println!("    [|");
        let mut pairs: Vec<String> = Vec::new();
        for code in 0..=0x10FFFFu32 {
            let Some(c) = char::from_u32(code) else { continue };
            let mapped: Vec<u32> = if upper { c.to_uppercase().map(u32::from).collect() } else { c.to_lowercase().map(u32::from).collect() };
            if mapped.len() == 1 && mapped[0] != code {
                pairs.push(format!("0x{code:X}; 0x{:X}", mapped[0]));
            }
        }
        for chunk in pairs.chunks(8) {
            println!("        {}", chunk.join("; "));
        }
        println!("    |]");
        println!();
    }
    for (name, doc, multi) in [
        ("upperSpecial", "`char::to_uppercase` where it is more than one character", true),
        ("lowerSpecial", "`char::to_lowercase` where it is more than one character", false),
    ] {
        println!("/// {doc}: code point, then the characters' code points.");
        println!("let {name}: (int * int[])[] =");
        println!("    [|");
        for code in 0..=0x10FFFFu32 {
            let Some(c) = char::from_u32(code) else { continue };
            let mapped: Vec<u32> =
                if multi { c.to_uppercase().map(u32::from).collect() } else { c.to_lowercase().map(u32::from).collect() };
            if mapped.len() > 1 {
                let list: Vec<String> = mapped.iter().map(|m| format!("0x{m:X}")).collect();
                println!("        0x{code:X}, [| {} |]", list.join("; "));
            }
        }
        println!("    |]");
        println!();
    }
}
